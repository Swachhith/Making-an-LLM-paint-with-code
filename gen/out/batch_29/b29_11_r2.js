async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#f1e4c8");
  brush.noStroke();
  brush.fillBleed(0.25);
  brush.fillTexture(0.45, 0.45);
  const wash = (c, o, pts, k) => {
    brush.fill(c, o);
    brush.beginShape(k || 0.5);
    pts.forEach(p => brush.vertex(p[0], p[1]));
    brush.endShape(true);
  };
  wash("#e89828", 205, [[-40,-40],[640,-40],[640,400],[-40,400]], 0.6);
  wash("#c85018", 190, [[-40,-40],[640,-40],[640,150],[-40,190]], 0.6);
  wash("#f8c860", 170, [[-40,240],[640,230],[640,400],[-40,400]], 0.6);
  wash("#3a1c1c", 215, [[-40,420],[-40,300],[110,245],[210,310],[330,215],[460,300],[640,245],[640,420]], 0.35);
  wash("#6a2a20", 190, [[-40,420],[-40,340],[130,300],[300,340],[460,330],[640,310],[640,420]], 0.4);
  for (let i = 0; i < 6; i++) {
    const y = 395 + i * 36;
    wash(i % 2 ? "#c85018" : "#e89828", 215, [[-40,y],[200,y-18],[400,y-6],[640,y-22],[640,y+40],[-40,y+42]], 0.5);
    wash("#2a1212", 205, [[-40,y+26],[300,y+12],[640,y+18],[640,y+42],[-40,y+46]], 0.4);
  }
  [[200,350,40],[250,338,52],[318,356,38],[368,342,48],[430,362,36],[470,352,30]].forEach((h, i) => {
    wash(i % 2 ? "#c85018" : "#241010", 235, [[h[0],h[1]+50],[h[0],h[1]],[h[0]+h[2]/2,h[1]-20],[h[0]+h[2],h[1]],[h[0]+h[2],h[1]+50]], 0.2);
  });
  wash("#241010", 215, [[170,400],[500,398],[500,420],[170,422]], 0.4);
  brush.fill("#fcd890", 220);
  [[222,378],[274,372],[336,382],[390,374]].forEach(p => brush.circle(p[0], p[1], 4, 0.3));
}

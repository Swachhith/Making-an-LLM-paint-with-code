async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#f3e8d2");
  brush.noStroke();
  brush.fillBleed(0.25);
  brush.fillTexture(0.4, 0.4);
  const wash = (c, o, pts, k) => {
    brush.fill(c, o);
    brush.beginShape(k || 0.5);
    pts.forEach(p => brush.vertex(p[0], p[1]));
    brush.endShape(true);
  };
  // amber backdrop on left third, with a vertical dark stroke accent
  wash("#e09020", 190, [[-40,40],[300,60],[320,640],[-40,640]], 0.7);
  wash("#c87010", 130, [[-40,300],[300,280],[320,640],[-40,640]], 0.7);
  wash("#2a1410", 170, [[-40,555],[360,545],[370,600],[-40,610]], 0.6);
  // skirt, layered flares
  wash("#9a0c18", 215, [[165,290],[235,290],[330,420],[320,520],[240,548],[150,520],[60,545],[40,450]]);
  wash("#d01a20", 210, [[180,320],[230,320],[305,430],[270,520],[185,505],[110,525],[85,455]]);
  wash("#f04830", 170, [[200,380],[240,420],[260,500],[205,495],[160,440]]);
  wash("#600810", 200, [[172,400],[205,430],[185,520],[140,505]]);
  wash("#600810", 190, [[240,430],[285,470],[270,525],[235,510]]);
  // bodice
  wash("#8a0a14", 220, [[172,210],[228,210],[236,300],[164,300]]);
  // arms
  wash("#d89030", 205, [[226,218],[268,140],[292,155],[248,245]]);
  wash("#d89030", 205, [[170,220],[120,185],[130,160],[190,200]]);
  brush.fill("#d89030", 210);
  brush.circle(200, 183, 22, 0.6);
  brush.fill("#1c1210", 235);
  brush.circle(200, 166, 21, 0.8);
  brush.circle(224, 160, 13, 0.8);
  wash("#1c1210", 210, [[148,520],[182,520],[174,562],[138,566]], 0.3);
  wash("#1c1210", 210, [[225,525],[260,520],[270,560],[232,565]], 0.3);
}

async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#12161c");
  brush.noStroke();
  brush.fillBleed(0.25);
  brush.fillTexture(0.4, 0.4);
  const wash = (c, o, pts, k) => {
    brush.fill(c, o);
    brush.beginShape(k || 0.5);
    pts.forEach(p => brush.vertex(p[0], p[1]));
    brush.endShape(true);
  };
  wash("#e8602a", 225, [[-40,-40],[640,-40],[640,430],[-40,430]], 0.6);
  wash("#f8a850", 225, [[-40,170],[640,210],[640,430],[-40,430]], 0.6);
  wash("#fcd890", 200, [[-40,290],[640,300],[640,430],[-40,430]], 0.6);
  wash("#7a2a70", 215, [[-40,-40],[640,-40],[640,110],[-40,90]], 0.6);
  // distant ridge
  wash("#5a4a78", 215, [[-40,430],[-40,340],[60,300],[140,345],[240,430]], 0.4);
  wash("#3a3258", 200, [[-40,430],[-40,380],[100,370],[170,430]], 0.4);
  // big cliff
  wash("#161a24", 245, [[240,640],[290,400],[360,200],[420,40],[500,90],[640,150],[640,640]], 0.35);
  wash("#2c3240", 220, [[320,640],[350,420],[410,250],[430,70],[480,100],[470,360],[520,640]], 0.35);
  wash("#d87038", 190, [[366,210],[420,50],[446,80],[400,250]], 0.35);
  wash("#10141c", 200, [[500,640],[520,400],[560,200],[640,200],[640,640]], 0.35);
  // waterfall
  wash("#c8def0", 240, [[420,200],[452,200],[466,490],[414,490]], 0.3);
  wash("#f4f9fc", 225, [[430,215],[444,215],[452,480],[428,480]], 0.3);
  wash("#9ab8d8", 170, [[418,300],[428,300],[424,480],[414,480]], 0.3);
  brush.fill("#c8def0", 215);
  brush.circle(440, 500, 40, 1.4);
  brush.fill("#f4f9fc", 190);
  brush.circle(425, 495, 22, 1.4);
  // dark foreground rocks
  wash("#0a0e14", 245, [[-40,640],[-40,525],[150,505],[300,515],[420,530],[640,520],[640,640]], 0.4);
  wash("#1c2a38", 180, [[-40,600],[200,560],[420,580],[640,570],[640,640],[-40,640]], 0.5);
}

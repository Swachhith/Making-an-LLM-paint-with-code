async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#eee4d2");
  brush.noStroke();
  brush.fillBleed(0.25);
  brush.fillTexture(0.45, 0.45);
  const wash = (c, o, pts, k) => {
    brush.fill(c, o);
    brush.beginShape(k || 0.5);
    pts.forEach(p => brush.vertex(p[0], p[1]));
    brush.endShape(true);
  };
  wash("#c88050", 205, [[-40,-40],[640,-40],[640,305],[-40,305]], 0.6);
  wash("#b05a40", 190, [[-40,150],[640,185],[640,305],[-40,305]], 0.6);
  wash("#d8a868", 170, [[-40,235],[640,245],[640,305],[-40,305]], 0.6);
  wash("#6a5a7a", 180, [[-40,-40],[640,-40],[640,90],[-40,70]], 0.6);
  // mountain with sun and shade side
  wash("#7a3a2a", 235, [[40,305],[170,190],[270,90],[330,150],[440,215],[580,305]], 0.3);
  wash("#4a2a2a", 225, [[270,90],[330,150],[440,215],[580,305],[320,305]], 0.3);
  wash("#a85a30", 170, [[100,305],[190,210],[262,110],[255,305]], 0.3);
  wash("#5a4a30", 210, [[-40,290],[640,288],[640,322],[-40,322]], 0.4);
  // water and reflection
  wash("#a08068", 205, [[-40,318],[640,318],[640,640],[-40,640]], 0.5);
  wash("#7a3a2a", 215, [[40,322],[170,438],[270,540],[330,478],[440,412],[580,322]], 0.35);
  wash("#4a2a2a", 205, [[270,540],[330,478],[440,412],[580,322],[320,322]], 0.35);
  wash("#d8a868", 190, [[-40,340],[640,336],[640,358],[-40,364]], 0.4);
  wash("#8a6a58", 180, [[-40,430],[640,425],[640,450],[-40,458]], 0.4);
  wash("#c88050", 170, [[-40,520],[640,515],[640,545],[-40,552]], 0.4);
  wash("#5a4a30", 180, [[-40,590],[640,585],[640,640],[-40,640]], 0.4);
}

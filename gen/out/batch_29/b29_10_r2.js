async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#efe6da");
  brush.noStroke();
  brush.fillBleed(0.25);
  brush.fillTexture(0.4, 0.4);
  const wash = (c, o, pts, k) => {
    brush.fill(c, o);
    brush.beginShape(k || 0.5);
    pts.forEach(p => brush.vertex(p[0], p[1]));
    brush.endShape(true);
  };
  wash("#e0602a", 215, [[-40,-40],[640,-40],[640,390],[-40,390]], 0.6);
  wash("#f8b050", 215, [[-40,220],[640,230],[640,390],[-40,390]], 0.6);
  wash("#fce090", 190, [[-40,310],[640,315],[640,390],[-40,390]], 0.6);
  wash("#6a2a58", 205, [[-40,-40],[640,-40],[640,120],[-40,100]], 0.6);
  brush.fill("#f8d890", 190);
  brush.circle(470, 270, 40, 0.8);
  wash("#2a1228", 235, [[-40,640],[-40,398],[200,385],[640,392],[640,640]], 0.45);
  wash("#5a2a40", 190, [[-40,470],[640,455],[640,540],[-40,560]], 0.5);
  wash("#1a0a1c", 215, [[-40,640],[-40,560],[640,545],[640,640]], 0.5);
  // road
  wash("#9a5a50", 175, [[290,400],[318,400],[470,640],[110,640]], 0.4);
  wash("#d89060", 150, [[298,404],[310,404],[380,640],[230,640]], 0.4);
  // alley of houses, small
  wash("#0e0612", 240, [[205,402],[205,350],[225,330],[250,350],[255,402]], 0.2);
  wash("#0e0612", 240, [[255,402],[255,340],[275,318],[300,340],[300,402]], 0.2);
  wash("#0e0612", 240, [[318,402],[318,335],[340,312],[365,335],[365,402]], 0.2);
  wash("#0e0612", 240, [[365,402],[365,350],[385,332],[408,350],[408,402]], 0.2);
  wash("#0e0612", 210, [[300,402],[305,365],[318,365],[320,402]], 0.2);
  brush.fill("#fcd070", 235);
  [[230,370],[275,365],[340,360],[388,372]].forEach(p => brush.circle(p[0], p[1], 4, 0.3));
  wash("#0e0612", 220, [[240,300],[245,330],[260,330],[258,300]], 0.2);
}

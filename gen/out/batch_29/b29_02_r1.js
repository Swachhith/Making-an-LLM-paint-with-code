async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#ece6e0");
  brush.noStroke();
  brush.fillBleed(0.25);
  brush.fillTexture(0.4, 0.4);
  const wash = (c, o, pts) => {
    brush.fill(c, o);
    brush.beginShape(0.5);
    pts.forEach(p => brush.vertex(p[0], p[1]));
    brush.endShape(true);
  };
  // sky
  wash("#e04a18", 210, [[-40,-40],[640,-40],[640,305],[-40,305]]);
  wash("#f8a030", 200, [[-40,140],[640,170],[640,305],[-40,305]]);
  wash("#fcd060", 170, [[-40,230],[640,240],[640,305],[-40,305]]);
  wash("#4a1a6a", 215, [[-40,-40],[640,-40],[640,80],[-40,100]]);
  wash("#7a2a80", 150, [[-40,50],[640,40],[640,120],[-40,140]]);
  // mirror
  wash("#e04a18", 190, [[-40,300],[640,300],[640,640],[-40,640]]);
  wash("#f8a030", 190, [[-40,305],[640,305],[640,420],[-40,440]]);
  wash("#fcd060", 160, [[-40,305],[640,305],[640,370],[-40,360]]);
  wash("#4a1a6a", 215, [[-40,500],[640,490],[640,640],[-40,640]]);
  // cracked flat streaks
  for (let i = 0; i < 6; i++) wash("#a02a30", 120, [[-40,330+i*45],[640,326+i*45],[640,340+i*45],[-40,346+i*45]]);
  // river converging to vanishing point
  wash("#180a28", 230, [[290,300],[314,300],[560,640],[30,640]]);
  wash("#f08a30", 170, [[298,304],[308,304],[430,640],[180,640]]);
  wash("#fcd060", 160, [[300,306],[306,306],[360,640],[250,640]]);
  // silhouette ridges
  wash("#140a20", 235, [[-40,305],[-40,262],[80,278],[200,290],[285,302]]);
  wash("#140a20", 235, [[318,305],[400,288],[500,268],[640,258],[640,305]]);
  wash("#140a20", 235, [[-40,305],[200,296],[285,300],[310,305]]);
  // silhouette: figure + dead shrub
  wash("#0c0614", 240, [[395,560],[408,470],[432,470],[448,560]]);
  brush.fill("#0c0614", 240);
  brush.circle(420, 452, 11, 0.5);
  wash("#0c0614", 200, [[90,580],[110,520],[150,515],[160,580]]);
  brush.circle(130, 505, 22, 1.4);
}

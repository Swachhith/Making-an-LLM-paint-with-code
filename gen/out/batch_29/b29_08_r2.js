async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#0c0e2c");
  brush.noStroke();
  brush.fillBleed(0.25);
  brush.fillTexture(0.4, 0.4);
  const wash = (c, o, pts, k) => {
    brush.fill(c, o);
    brush.beginShape(k || 0.5);
    pts.forEach(p => brush.vertex(p[0], p[1]));
    brush.endShape(true);
  };
  wash("#2020c0", 225, [[-40,-40],[640,-40],[640,430],[-40,430]], 0.6);
  wash("#8a20b0", 210, [[-40,120],[640,40],[640,340],[-40,380]], 0.6);
  wash("#f02a80", 185, [[260,230],[640,170],[640,430],[200,430]], 0.6);
  wash("#ff8a30", 150, [[380,320],[640,290],[640,430],[340,430]], 0.6);
  wash("#10107a", 170, [[-40,-40],[640,-40],[640,90],[-40,110]], 0.6);
  const st = [[60,40],[140,110],[240,30],[330,80],[420,30],[540,110],[580,40],[80,200],[480,160],[30,290],[570,250],[200,190],[360,150],[290,200]];
  brush.fill("#fff6c8", 240);
  st.forEach((s, i) => brush.circle(s[0], s[1], 2.5 + (i % 3) * 1.5, 0.3));
  brush.fill("#fff6c8", 215);
  brush.circle(510, 70, 26, 0.4);
  wash("#063828", 240, [[-40,640],[-40,430],[200,410],[420,450],[640,490],[640,640]], 0.5);
  wash("#0a6a3a", 170, [[-40,470],[200,440],[420,480],[640,520],[640,560],[-40,560]], 0.5);
  // figure, large, waist-up, face tilted up
  wash("#f0601a", 235, [[90,640],[110,450],[190,395],[300,415],[340,640]], 0.5);
  wash("#b02a08", 215, [[240,640],[250,430],[300,418],[340,640]], 0.5);
  wash("#ff9a40", 150, [[120,640],[130,470],[180,430],[190,640]], 0.5);
  wash("#f2b488", 235, [[196,415],[212,350],[260,350],[276,420]], 0.4);
  brush.fill("#f2b488", 240);
  brush.circle(238, 305, 40, 0.5);
  brush.fill("#18080e", 240);
  brush.circle(226, 282, 38, 0.8);
  brush.circle(256, 296, 20, 0.8);
  wash("#f0601a", 225, [[270,440],[335,320],[375,335],[315,465]], 0.5);
  brush.fill("#f2b488", 235);
  brush.circle(372, 318, 18, 0.5);
}

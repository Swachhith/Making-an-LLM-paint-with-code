async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#f5ead2");
  brush.noStroke();
  brush.fillBleed(0.25);
  brush.fillTexture(0.45, 0.45);
  const wash = (c, o, pts, k) => {
    brush.fill(c, o);
    brush.beginShape(k || 0.5);
    pts.forEach(p => brush.vertex(p[0], p[1]));
    brush.endShape(true);
  };
  wash("#f0a840", 215, [[-40,-40],[640,-40],[640,640],[-40,640]], 0.6);
  wash("#e07030", 190, [[-40,-40],[640,-40],[640,180],[-40,260]], 0.6);
  wash("#fcd070", 170, [[300,200],[640,150],[640,450],[300,450]], 0.6);
  wash("#9a5a5a", 200, [[-40,600],[-40,420],[160,350],[300,420],[440,380],[640,430],[640,600]], 0.4);
  wash("#7a4a5a", 190, [[-40,600],[-40,490],[200,450],[420,500],[640,470],[640,600]], 0.4);
  wash("#4a2e24", 235, [[-40,640],[-40,520],[200,495],[400,540],[640,505],[640,640]], 0.4);
  // trunk: big twisted mass
  wash("#5a2a14", 225, [[200,560],[270,440],[200,340],[270,230],[350,235],[310,340],[375,440],[420,560]], 0.6);
  wash("#8a4a20", 205, [[250,550],[300,440],[245,345],[300,250],[330,345],[360,440],[385,550]], 0.6);
  wash("#d88a40", 140, [[270,520],[310,440],[275,350],[305,270],[318,350]], 0.6);
  wash("#3a1a0a", 200, [[330,545],[350,440],[320,350],[345,260],[365,350],[395,440],[420,560]], 0.6);
  // limbs sweeping
  wash("#5a2a14", 215, [[290,300],[170,240],[60,185],[-20,170],[-20,205],[70,215],[180,275],[300,340]], 0.5);
  wash("#5a2a14", 215, [[330,290],[450,215],[540,185],[640,170],[640,215],[545,235],[460,265],[340,350]], 0.5);
  wash("#5a2a14", 205, [[300,260],[240,150],[255,70],[300,65],[310,150],[330,250]], 0.5);
  const pts = [[30,170],[90,200],[20,215],[160,240],[560,180],[500,225],[440,170],[300,70],[350,110],[250,120],[200,170],[580,215]];
  pts.forEach((p, i) => {
    brush.fill(i % 2 ? "#2a5a1a" : "#5a7a10", 205);
    brush.circle(p[0], p[1], 40 + (i % 3) * 10, 1.4);
  });
  brush.fill("#b88a10", 150);
  brush.circle(300, 90, 45, 1.3);
}

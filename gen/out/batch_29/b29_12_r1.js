async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#f5e9d2");
  brush.noStroke();
  brush.fillBleed(0.25);
  brush.fillTexture(0.4, 0.4);
  const wash = (c, o, pts, k) => {
    brush.fill(c, o);
    brush.beginShape(k || 0.5);
    pts.forEach(p => brush.vertex(p[0], p[1]));
    brush.endShape(true);
  };
  wash("#e8a028", 195, [[200,30],[640,70],[620,540],[230,590]], 0.7);
  wash("#d85a28", 175, [[280,340],[640,310],[640,640],[270,640]], 0.7);
  wash("#f0c050", 150, [[320,60],[560,90],[540,300],[330,280]], 0.7);
  wash("#2a3818", 225, [[400,640],[396,380],[424,380],[436,640]], 0.5);
  wash("#42561e", 210, [[408,600],[320,490],[285,350],[375,430],[420,540]], 0.6);
  wash("#42561e", 210, [[420,580],[490,480],[535,380],[515,490],[432,610]], 0.6);
  wash("#1e2a10", 190, [[400,600],[340,500],[330,420],[385,490]], 0.6);
  // tulip, dark purple-black layered
  wash("#2a1030", 225, [[345,260],[350,170],[400,115],[415,215],[385,345],[342,330]], 0.7);
  wash("#2a1030", 225, [[480,260],[470,170],[425,115],[412,215],[440,345],[485,330]], 0.7);
  wash("#4a2050", 210, [[372,345],[365,200],[412,140],[460,200],[452,345],[412,382]], 0.7);
  wash("#12061a", 235, [[392,350],[398,225],[428,225],[432,350]], 0.6);
  wash("#6a2a60", 160, [[375,300],[372,210],[395,170],[400,300]], 0.6);
  brush.fill("#b8302a", 150);
  brush.circle(412, 150, 24, 1.2);
}

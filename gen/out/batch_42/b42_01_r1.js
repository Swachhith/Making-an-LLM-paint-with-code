async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#dfe4ee");
  brush.noStroke();
  const S = (pts, c, o, b) => { brush.fill(c, o); brush.fillBleed(b); brush.fillTexture(0.5, 0.4); brush.beginShape(0.5); pts.forEach(p => brush.vertex(p[0], p[1])); brush.endShape(true); };
  S([[0,0],[600,0],[600,400],[0,400]], "#1f2a78", 200, 0.3);
  S([[0,0],[600,0],[600,260],[0,300]], "#141d5a", 190, 0.3);
  S([[0,150],[600,120],[600,380],[0,400]], "#4a5cb0", 160, 0.3);
  for (let i = 0; i < 50; i++) { brush.fill("#ffffff", 230); brush.fillBleed(0.1); brush.circle(10 + (i * 71) % 590, 20 + (i * 43) % 360, 2 + (i % 3), 0.5); }
  S([[0,380],[150,350],[330,372],[470,345],[600,365],[600,600],[0,600]], "#f2f4fa", 235, 0.25);
  S([[0,430],[300,405],[600,425],[600,600],[0,600]], "#b8c2e4", 190, 0.3);
  S([[0,500],[250,480],[600,505],[600,600],[0,600]], "#2d3a96", 200, 0.3);
  S([[0,560],[600,550],[600,600],[0,600]], "#141d5a", 210, 0.3);
  S([[262,376],[340,376],[340,404],[262,404]], "#141d5a", 235, 0.2);
  S([[252,378],[300,346],[350,378]], "#0a1040", 240, 0.15);
  S([[282,384],[306,384],[306,402],[282,402]], "#ff9a00", 255, 0.1);
  brush.fill("#ff9a00", 200); brush.circle(294, 393, 5, 0.3);
  S([[372,368],[420,368],[420,402],[372,402]], "#1f2a78", 220, 0.2);
  S([[150,390],[172,370],[196,390],[196,404],[150,404]], "#141d5a", 220, 0.2);
  brush.fill("#141d5a", 220); brush.circle(84, 386, 22, 0.6); brush.circle(110, 392, 16, 0.6); brush.circle(520, 384, 24, 0.6);
  S([[250,410],[340,408],[420,440],[260,450]], "#ff9a00", 90, 0.3);
}

async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#e6eef2");
  brush.noStroke();
  const S = (pts, c, o, b) => { brush.fill(c, o); brush.fillBleed(b); brush.fillTexture(0.5, 0.4); brush.beginShape(0.4); pts.forEach(p => brush.vertex(p[0], p[1])); brush.endShape(true); if (o >= 215) { brush.fill(c, o - 40); brush.beginShape(0.5); pts.forEach(p => brush.vertex(p[0] + 2, p[1] + 1)); brush.endShape(true); } };
  S([[0,0],[600,0],[600,600],[0,600]], "#a8cce0", 150, 0.3);
  S([[0,0],[600,0],[600,240],[0,280]], "#7fb0d0", 150, 0.3);
  S([[0,60],[130,30],[210,190],[190,430],[0,440]], "#2f7f78", 215, 0.3);
  S([[600,50],[470,20],[390,190],[420,430],[600,440]], "#206a6a", 215, 0.3);
  S([[0,150],[110,110],[170,260],[130,420],[0,430]], "#1a5658", 190, 0.3);
  S([[600,160],[500,120],[440,260],[470,420],[600,430]], "#164a58", 190, 0.3);
  S([[210,300],[390,300],[390,440],[210,440]], "#6aa8a0", 120, 0.3);
  // plinth
  S([[40,525],[560,520],[580,590],[20,590]], "#5a7a92", 220, 0.2);
  S([[90,440],[510,440],[510,530],[90,530]], "#e2ecf0", 235, 0.15);
  S([[90,440],[510,440],[510,478],[90,478]], "#4a6a8c", 130, 0.2);
  S([[100,500],[500,500],[500,530],[100,530]], "#6a8aa8", 130, 0.2);
  for (let i = 0; i < 5; i++) S([[125+i*85,448],[150+i*85,448],[150+i*85,525],[125+i*85,525]], "#2f4f78", 225, 0.2);
  S([[190,470],[410,470],[410,525],[190,525]], "#1a2a4a", 150, 0.2);
  // tiered roofs
  S([[30,450],[300,360],[570,450],[500,425],[300,392],[100,425]], "#1f3a62", 235, 0.2);
  S([[100,372],[300,272],[500,372],[430,350],[300,312],[170,350]], "#1f3a62", 230, 0.2);
  S([[180,290],[300,195],[420,290],[360,278],[300,238],[240,278]], "#1f3a62", 230, 0.2);
  S([[280,200],[300,150],[320,200]], "#1f3a62", 235, 0.15);
  S([[250,330],[350,330],[360,370],[240,370]], "#a8c4d8", 160, 0.2);
  S([[60,440],[540,440],[490,460],[110,460]], "#3a5a82", 190, 0.2);
  S([[0,420],[600,420],[600,445],[0,445]], "#ffffff", 80, 0.3);
}

async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#e8eef0");
  brush.noStroke();
  const P = (pts, c, o, b, t) => { brush.fill(c, o); brush.fillBleed(b); brush.fillTexture(t, t); brush.beginShape(0.5); pts.forEach(p => brush.vertex(p[0], p[1])); brush.endShape(true); };
  P([[0,0],[600,0],[600,600],[0,600]], "#1d6a74", 120, 0.3, 0.4);
  P([[0,0],[600,0],[600,200],[0,260]], "#2b3a8a", 120, 0.3, 0.4);
  P([[0,480],[600,470],[600,600],[0,600]], "#16335e", 190, 0.3, 0.5);
  // trunk
  P([[270,600],[330,600],[320,420],[300,330],[285,420]], "#16335e", 220, 0.2, 0.4);
  P([[300,400],[200,300],[170,260],[215,285],[300,350]], "#16335e", 200, 0.2, 0.4);
  P([[300,400],[400,310],[430,270],[385,295],[300,350]], "#16335e", 200, 0.2, 0.4);
  // crown
  P([[300,40],[420,70],[520,160],[560,280],[520,400],[420,450],[300,470],[180,450],[80,400],[40,280],[80,160],[180,70]], "#e8b800", 190, 0.3, 0.5);
  P([[300,80],[400,110],[480,190],[510,290],[470,380],[380,420],[300,430],[220,420],[130,380],[90,290],[120,190],[200,110]], "#f4d000", 200, 0.3, 0.5);
  P([[300,130],[380,160],[430,230],[440,310],[380,370],[300,380],[220,370],[160,310],[170,230],[220,160]], "#f7e04a", 190, 0.25, 0.5);
  P([[120,300],[200,260],[260,340],[200,420],[110,390]], "#c89000", 150, 0.3, 0.5);
  P([[420,160],[500,220],[510,320],[440,300]], "#c89000", 140, 0.3, 0.5);
  for (let i = 0; i < 18; i++) { brush.fill("#e8b800", 200); brush.fillBleed(0.2); brush.circle(40 + (i * 131) % 520, 500 + (i * 29) % 90, 8, 0.6); }
}

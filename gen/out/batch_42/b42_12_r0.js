async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#f1e6d0");
  brush.noStroke();
  const P = (pts, c, o, b, t) => { brush.fill(c, o); brush.fillBleed(b); brush.fillTexture(t, t); brush.beginShape(0.4); pts.forEach(p => brush.vertex(p[0], p[1])); brush.endShape(true); };
  P([[0,0],[600,0],[600,600],[0,600]], "#f0b070", 130, 0.3, 0.4);
  P([[0,0],[600,0],[600,200],[0,260]], "#e07a30", 120, 0.3, 0.4);
  P([[300,500],[360,260],[380,60],[460,40],[520,130],[580,300],[600,500]], "#4a2a1a", 90, 0.3, 0.4);
  // big peak left of centre? off-centre right
  P([[150,600],[250,380],[360,200],[430,80],[470,70],[520,180],[600,350],[600,600]], "#2b1810", 220, 0.2, 0.4);
  P([[430,80],[470,70],[520,180],[480,170],[455,130],[430,190],[400,150]], "#faf0e0", 235, 0.2, 0.3);
  P([[360,200],[430,190],[460,260],[420,330],[370,300]], "#faf0e0", 200, 0.25, 0.3);
  P([[470,200],[520,180],[580,320],[520,340],[480,260]], "#faf0e0", 190, 0.25, 0.3);
  P([[430,190],[520,180],[600,350],[600,600],[470,600],[470,350]], "#1a0e08", 160, 0.25, 0.4);
  P([[0,430],[120,400],[230,450],[260,600],[0,600]], "#e07a30", 150, 0.3, 0.5);
  P([[0,520],[300,500],[600,540],[600,600],[0,600]], "#2b1810", 200, 0.3, 0.5);
  [[400,290],[420,310],[440,330]].forEach(c => { P([[c[0],c[1]],[c[0]+16,c[1]],[c[0]+16,c[1]+22],[c[0],c[1]+22]], "#c8261a", 240, 0.1, 0.3); });
}

async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#f4ece0");
  brush.noStroke();
  const P = (pts, c, o, b, t) => { brush.fill(c, o); brush.fillBleed(b); brush.fillTexture(t, t); brush.beginShape(0.5); pts.forEach(p => brush.vertex(p[0], p[1])); brush.endShape(true); };
  P([[0,0],[600,0],[600,200],[0,200]], "#ff7a5a", 160, 0.3, 0.4);
  P([[0,100],[600,100],[600,260],[0,260]], "#ffc04a", 150, 0.3, 0.4);
  // sea
  P([[0,200],[600,200],[600,330],[0,330]], "#0b7a9a", 200, 0.3, 0.5);
  P([[0,250],[600,250],[600,320],[0,320]], "#0a9aa8", 170, 0.3, 0.5);
  // headland cliff
  P([[0,160],[140,120],[200,200],[150,330],[0,340]], "#1a3a2a", 210, 0.3, 0.5);
  P([[0,160],[90,140],[110,200],[0,230]], "#3a7a3a", 190, 0.3, 0.5);
  // black sand
  P([[0,330],[600,330],[600,600],[0,600]], "#1c1c24", 210, 0.3, 0.5);
  P([[0,380],[600,360],[600,600],[0,600]], "#0e0e16", 200, 0.3, 0.5);
  // wet shine + foam
  P([[0,355],[200,340],[400,350],[600,338],[600,372],[400,380],[200,372],[0,385]], "#ffffff", 220, 0.3, 0.4);
  P([[0,455],[250,430],[600,450],[600,490],[250,475],[0,500]], "#6a8aa8", 140, 0.3, 0.4);
  P([[100,540],[500,520],[560,600],[60,600]], "#c8264a", 110, 0.3, 0.4);
}

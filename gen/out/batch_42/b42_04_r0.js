async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#f3ead9");
  brush.noStroke();
  const P = (pts, c, o, b, t) => { brush.fill(c, o); brush.fillBleed(b); brush.fillTexture(t, t); brush.beginShape(0.6); pts.forEach(p => brush.vertex(p[0], p[1])); brush.endShape(true); };
  P([[0,0],[600,0],[600,600],[0,600]], "#7a0f26", 130, 0.3, 0.4);
  P([[0,380],[600,360],[600,600],[0,600]], "#120a0c", 200, 0.3, 0.5);
  P([[0,0],[600,0],[600,160],[0,200]], "#120a0c", 150, 0.3, 0.5);
  // arcing stem
  P([[20,560],[40,500],[120,380],[240,300],[360,270],[430,280],[420,320],[350,320],[250,350],[150,430],[80,520],[50,580]], "#c01740", 190, 0.25, 0.4);
  P([[40,560],[130,420],[250,330],[360,290],[420,300],[360,305],[260,355],[150,450],[70,560]], "#120a0c", 170, 0.25, 0.4);
  // lily pads
  P([[60,230],[150,210],[200,260],[130,300],[70,280]], "#120a0c", 200, 0.3, 0.5);
  P([[400,480],[500,450],[570,500],[500,550],[420,540]], "#120a0c", 200, 0.3, 0.5);
  // lily petals, left as paper centre
  const petals = [[[470,300],[440,200],[500,150],[540,210],[520,290]],[[470,300],[560,260],[590,190],[570,310]],[[470,310],[380,260],[350,190],[410,150],[450,230]],[[480,320],[560,360],[580,300]],[[470,320],[400,370],[380,310]]];
  petals.forEach((p, i) => { P(p, "#c01740", 150, 0.3, 0.4); P(p.map(q => [q[0]*0.6+470*0.4, q[1]*0.6+300*0.4]), "#7a0f26", 170, 0.25, 0.4); });
  brush.fill("#f6e7b8", 235); brush.fillBleed(0.15); brush.circle(475, 285, 22, 0.5);
}

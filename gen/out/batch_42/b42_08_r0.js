async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#0c1030");
  brush.noStroke();
  const P = (pts, c, o, b, t) => { brush.fill(c, o); brush.fillBleed(b); brush.fillTexture(t, t); brush.beginShape(0.4); pts.forEach(p => brush.vertex(p[0], p[1])); brush.endShape(true); };
  P([[0,0],[600,0],[600,380],[0,380]], "#2a2f9a", 190, 0.3, 0.4);
  P([[0,180],[600,160],[600,380],[0,380]], "#7a2fa8", 170, 0.3, 0.4);
  P([[0,280],[600,270],[600,400],[0,400]], "#e8506a", 170, 0.3, 0.4);
  P([[0,350],[600,340],[600,600],[0,600]], "#1a2a78", 200, 0.3, 0.5);
  P([[0,400],[600,390],[600,600],[0,600]], "#e8782a", 90, 0.3, 0.5);
  // silhouettes
  P([[0,340],[80,330],[120,300],[180,330],[200,380],[0,390]], "#05060f", 235, 0.15, 0.3);
  P([[430,360],[480,330],[520,340],[600,320],[600,390],[430,390]], "#05060f", 235, 0.15, 0.3);
  P([[290,330],[310,330],[310,200],[290,200]], "#05060f", 230, 0.15, 0.3);
  P([[300,215],[410,330],[300,330]], "#05060f", 230, 0.15, 0.3);
  P([[200,360],[360,360],[330,395],[230,395]], "#05060f", 235, 0.15, 0.3);
  P([[250,330],[270,330],[270,360],[250,360]], "#05060f", 235, 0.15, 0.3);
  P([[225,360],[400,365],[420,380],[220,380]], "#05060f", 235, 0.15, 0.3);
  // lights
  [[60,350],[150,345],[460,350],[560,345],[250,375],[340,375]].forEach(l => { brush.fill("#ffd24a", 240); brush.fillBleed(0.15); brush.circle(l[0], l[1], 4, 0.4); });
  brush.fill("#f4efe0", 240); brush.circle(480, 90, 22, 0.3);
  P([[100,420],[180,420],[170,520],[110,520]], "#ffb43a", 120, 0.3, 0.4);
  P([[440,420],[520,420],[510,520],[450,520]], "#ffb43a", 120, 0.3, 0.4);
}

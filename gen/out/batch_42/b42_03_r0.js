async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#f5e9d2");
  brush.noStroke();
  const P = (pts, c, o, b, t) => { brush.fill(c, o); brush.fillBleed(b); brush.fillTexture(t, t); brush.beginShape(0.5); pts.forEach(p => brush.vertex(p[0], p[1])); brush.endShape(true); };
  P([[0,0],[600,0],[600,330],[0,330]], "#f2b872", 150, 0.3, 0.4);
  P([[0,0],[600,0],[600,170],[0,190]], "#d9822b", 130, 0.3, 0.4);
  P([[0,330],[600,320],[600,600],[0,600]], "#d9822b", 150, 0.3, 0.5);
  P([[0,380],[600,360],[600,600],[0,600]], "#b8651b", 150, 0.3, 0.5);
  P([[0,480],[600,460],[600,600],[0,600]], "#2b1d14", 90, 0.3, 0.5);
  // trunk
  P([[285,350],[325,350],[335,300],[315,230],[300,200],[290,240],[272,300]], "#2b1d14", 230, 0.2, 0.4);
  P([[300,200],[270,160],[250,150],[285,185]], "#2b1d14", 220, 0.2, 0.4);
  P([[315,230],[360,190],[380,175],[345,225]], "#2b1d14", 220, 0.2, 0.4);
  P([[290,250],[240,230],[215,225],[240,255]], "#2b1d14", 220, 0.2, 0.4);
  // foliage on surviving side
  P([[330,230],[380,200],[420,215],[430,255],[390,285],[335,275]], "#b8651b", 200, 0.3, 0.5);
  P([[345,235],[385,215],[410,230],[400,260],[360,268]], "#d9822b", 210, 0.3, 0.5);
  P([[205,240],[240,215],[270,235],[260,275],[220,280]], "#b8651b", 200, 0.3, 0.5);
  P([[275,330],[335,330],[340,365],[270,365]], "#2b1d14", 160, 0.3, 0.4);
  // fence posts
  for (let i = 0; i < 6; i++) P([[40+i*90,400],[56+i*90,400],[56+i*90,440],[40+i*90,440]], "#2b1d14", 140, 0.2, 0.3);
}

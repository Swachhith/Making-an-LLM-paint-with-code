async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#efe3cf");
  brush.noStroke();
  const S = (pts, c, o, b) => { brush.fill(c, o); brush.fillBleed(b); brush.fillTexture(0.5, 0.4); brush.beginShape(0.6); pts.forEach(p => brush.vertex(p[0], p[1])); brush.endShape(true); };
  S([[0,0],[600,0],[600,600],[0,600]], "#8a0f2a", 170, 0.3);
  S([[0,0],[600,0],[600,300],[0,360]], "#5a0a1e", 170, 0.3);
  S([[0,360],[600,340],[600,600],[0,600]], "#0c0709", 225, 0.3);
  S([[0,380],[600,360],[600,600],[0,600]], "#0c0709", 220, 0.3);
  // arcing stem, thick, from lower left over to flower
  S([[10,590],[30,490],[110,370],[230,285],[350,245],[440,250],[440,300],[370,310],[270,345],[170,420],[100,510],[70,600]], "#0c0709", 235, 0.2);
  S([[40,590],[60,500],[130,400],[250,310],[360,275],[430,280],[360,300],[270,340],[170,430],[100,520]], "#e8184a", 150, 0.25);
  // pads
  S([[60,200],[150,180],[215,230],[150,290],[80,270]], "#0c0709", 225, 0.3);
  S([[390,470],[500,440],[585,495],[510,560],[410,545]], "#0c0709", 230, 0.3);
  S([[390,470],[470,455],[470,500],[420,520]], "#d4153f", 120, 0.3);
  // lily: leave paper for white petals, surround with crimson shadow
  const C = [480, 290];
  const pet = [[[480,290],[440,180],[480,110],[530,170],[520,280]],[[485,300],[570,240],[600,160],[600,300]],[[470,300],[370,250],[340,160],[410,120],[450,210]],[[490,310],[580,350],[590,290]],[[465,310],[390,370],[370,300]]];
  pet.forEach(p => { S(p.map(q => [q[0]*1.08-C[0]*0.08, q[1]*1.08-C[1]*0.08]), "#a8102f", 230, 0.25); });
  pet.forEach(p => { S(p.map(q => [q[0]*0.8+C[0]*0.2, q[1]*0.8+C[1]*0.2]), "#f3e6c6", 235, 0.2); });
  S([[460,275],[500,275],[495,305],[465,305]], "#f5d98a", 245, 0.15);
  brush.fill("#fff3c8", 245); brush.fillBleed(0.1); brush.circle(480, 290, 14, 0.4);
}

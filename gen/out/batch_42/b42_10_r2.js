async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#f1e6d6");
  brush.noStroke();
  const S = (pts, c, o, b) => { brush.fill(c, o); brush.fillBleed(b); brush.fillTexture(0.5, 0.4); brush.beginShape(0.5); pts.forEach(p => brush.vertex(p[0], p[1])); brush.endShape(true); if (o >= 215) { brush.fill(c, o - 40); brush.beginShape(0.5); pts.forEach(p => brush.vertex(p[0] + 2, p[1] + 1)); brush.endShape(true); } };
  S([[0,0],[600,0],[600,200],[0,220]], "#ff5a3a", 200, 0.3);
  S([[0,90],[600,80],[600,250],[0,260]], "#ffb020", 190, 0.3);
  S([[0,200],[600,190],[600,340],[0,350]], "#0a6a9a", 225, 0.3);
  S([[0,260],[600,250],[600,330],[0,340]], "#00a8a8", 190, 0.3);
  // sea stack and cliff
  S([[0,140],[110,90],[190,170],[160,350],[0,360]], "#10301f", 235, 0.25);
  S([[0,140],[80,110],[110,190],[0,240]], "#2f7a3a", 210, 0.3);
  S([[470,210],[510,150],[540,230],[550,340],[470,340]], "#10301f", 230, 0.25);
  // sand
  S([[0,340],[600,340],[600,600],[0,600]], "#1a1a26", 235, 0.3);
  S([[0,420],[600,400],[600,600],[0,600]], "#0c0c18", 230, 0.3);
  S([[0,510],[600,490],[600,600],[0,600]], "#05050e", 230, 0.3);
  S([[0,355],[200,342],[400,352],[600,340],[600,375],[400,385],[200,376],[0,390]], "#ffffff", 240, 0.3);
  S([[0,445],[250,425],[600,445],[600,480],[250,465],[0,490]], "#7a9ac0", 190, 0.3);
  S([[60,520],[520,500],[570,600],[40,600]], "#e0264a", 130, 0.3);
  S([[220,380],[360,375],[380,430],[200,440]], "#ffb020", 90, 0.3);
}

async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#eef3f5");
  brush.noStroke();
  const P = (pts, c, o, b, t) => { brush.fill(c, o); brush.fillBleed(b); brush.fillTexture(t, t); brush.beginShape(0.4); pts.forEach(p => brush.vertex(p[0], p[1])); brush.endShape(true); };
  P([[0,0],[600,0],[600,600],[0,600]], "#bcd7e6", 140, 0.3, 0.4);
  P([[0,0],[600,0],[600,200],[0,240]], "#9ec3da", 130, 0.3, 0.4);
  // trees behind
  P([[0,120],[120,60],[200,200],[170,420],[0,420]], "#4f8f86", 190, 0.3, 0.5);
  P([[600,100],[470,50],[400,200],[430,420],[600,420]], "#3f7f7c", 190, 0.3, 0.5);
  P([[30,200],[100,150],[150,260],[100,400],[20,400]], "#2f6a6a", 150, 0.3, 0.5);
  // temple base
  P([[70,520],[530,520],[550,580],[50,580]], "#8fa3ad", 200, 0.2, 0.4);
  P([[110,440],[490,440],[490,525],[110,525]], "#d9e3e8", 200, 0.2, 0.4);
  P([[110,440],[490,440],[490,480],[110,480]], "#6c8aa0", 120, 0.2, 0.4);
  // pillars
  for (let i = 0; i < 5; i++) P([[135+i*80,445],[155+i*80,445],[155+i*80,520],[135+i*80,520]], "#4a6a88", 190, 0.2, 0.3);
  // roofs
  P([[60,445],[300,370],[540,445],[480,430],[300,395],[120,430]], "#2c4a6e", 220, 0.2, 0.4);
  P([[120,370],[300,285],[480,370],[420,355],[300,320],[180,355]], "#2c4a6e", 215, 0.2, 0.4);
  P([[190,290],[300,205],[410,290],[360,282],[300,245],[240,282]], "#2c4a6e", 215, 0.2, 0.4);
  P([[285,205],[300,170],[315,205]], "#2c4a6e", 220, 0.15, 0.3);
  P([[75,440],[525,440],[480,455],[120,455]], "#6c8aa0", 160, 0.2, 0.3);
}

  // hat
  P([[190,225],[300,195],[410,225],[380,245],[300,235],[220,245]], "#f4d35e", 235, 0.2, 0.4);
  P([[245,215],[255,150],[345,150],[355,215],[300,205]], "#f4d35e", 230, 0.2, 0.4);
  P([[247,200],[353,200],[354,218],[246,218]], "#c8102e", 240, 0.2, 0.3);

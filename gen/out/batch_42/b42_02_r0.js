  P([[470,120],[580,130],[590,300],[480,300]], "#f4c20d", 200, 0.25, 0.4);
  // body striped shirt
  P([[170,600],[190,430],[250,390],[350,390],[410,430],[430,600]], "#ffffff", 120, 0.2, 0.3);
  P([[170,600],[190,430],[250,390],[350,390],[410,430],[430,600]], "#c8102e", 190, 0.25, 0.4);
  for (let i = 0; i < 6; i++) P([[175+i*2,450+i*26],[425-i*2,450+i*26],[425-i*2,468+i*26],[175+i*2,468+i*26]], "#14213d", 200, 0.2, 0.3);

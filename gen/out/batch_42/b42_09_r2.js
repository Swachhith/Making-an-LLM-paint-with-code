async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#dfe9ec");
  brush.noStroke();
  const S = (pts, c, o, b) => { brush.fill(c, o); brush.fillBleed(b); brush.fillTexture(0.5, 0.4); brush.beginShape(0.5); pts.forEach(p => brush.vertex(p[0], p[1])); brush.endShape(true); if (o >= 215) { brush.fill(c, o - 40); brush.beginShape(0.5); pts.forEach(p => brush.vertex(p[0] + 2, p[1] + 1)); brush.endShape(true); } };
  S([[0,0],[600,0],[600,600],[0,600]], "#1d7a84", 150, 0.3);
  S([[0,0],[600,0],[600,240],[0,300]], "#2b3a9a", 190, 0.3);
  S([[0,440],[600,430],[600,600],[0,600]], "#12285a", 215, 0.3);
  S([[0,520],[600,510],[600,600],[0,600]], "#0a1840", 215, 0.3);
  // trunk
  S([[262,600],[338,600],[322,430],[306,340],[290,430]], "#0e2048", 240, 0.2);
  S([[300,420],[210,310],[180,265],[222,290],[300,360]], "#0e2048", 230, 0.2);
  S([[300,420],[395,320],[425,278],[388,305],[300,365]], "#0e2048", 230, 0.2);
  // crown, three passes
  S([[300,30],[430,60],[530,160],[570,280],[530,400],[420,455],[300,475],[180,455],[75,400],[35,280],[75,160],[175,60]], "#d9a400", 195, 0.3);
  S([[300,75],[410,100],[490,185],[520,290],[470,385],[380,425],[300,435],[215,425],[130,385],[85,290],[115,190],[200,105]], "#f0c400", 215, 0.3);
  S([[300,125],[385,150],[435,230],[445,305],[385,370],[300,385],[215,370],[160,305],[165,230],[220,155]], "#fbe45a", 205, 0.25);
  S([[100,300],[200,255],[260,345],[200,435],[90,395]], "#b87800", 170, 0.3);
  S([[440,150],[525,220],[535,330],[450,310]], "#b87800", 160, 0.3);
  S([[240,190],[310,160],[330,240],[270,260]], "#fff3a0", 150, 0.25);
  for (let i = 0; i < 22; i++) { brush.fill("#e8b800", 220); brush.fillBleed(0.2); brush.circle(30 + (i * 127) % 540, 470 + (i * 31) % 120, 8, 0.6); }
  S([[0,445],[200,430],[420,440],[600,430],[600,470],[0,480]], "#1d7a84", 140, 0.3);
}

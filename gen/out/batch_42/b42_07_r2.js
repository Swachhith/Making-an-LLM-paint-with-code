async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function draw() {
  translate(-width / 2, -height / 2);
  background("#e8eff0");
  brush.noStroke();
  const S = (pts, c, o, b) => { brush.fill(c, o); brush.fillBleed(b); brush.fillTexture(0.5, 0.4); brush.beginShape(0.5); pts.forEach(p => brush.vertex(p[0], p[1])); brush.endShape(true); if (o >= 215) { brush.fill(c, o - 40); brush.beginShape(0.5); pts.forEach(p => brush.vertex(p[0] + 2, p[1] + 1)); brush.endShape(true); } };
  S([[0,0],[600,0],[600,280],[0,280]], "#cfe6dc", 190, 0.3);
  S([[200,60],[420,50],[440,260],[180,270]], "#f4f7e8", 190, 0.3);
  S([[0,200],[600,190],[600,300],[0,310]], "#8fb59a", 190, 0.3);
  // river/path leading away
  S([[285,265],[318,265],[490,600],[110,600]], "#a8c6e6", 215, 0.25);
  S([[290,270],[312,270],[400,600],[210,600]], "#f0f6fb", 150, 0.25);
  // carpet
  S([[0,280],[285,268],[110,600],[0,600]], "#3a4cc0", 215, 0.3);
  S([[318,268],[600,285],[600,600],[490,600]], "#3a4cc0", 215, 0.3);
  S([[0,350],[250,310],[70,600],[0,600]], "#2a2f9a", 190, 0.3);
  S([[600,350],[350,310],[530,600],[600,600]], "#2a2f9a", 190, 0.3);
  S([[0,450],[130,430],[40,600],[0,600]], "#5a2f9a", 150, 0.3);
  S([[600,450],[470,430],[560,600],[600,600]], "#5a2f9a", 150, 0.3);
  // trunks
  [[55,100],[180,50],[430,50],[545,110]].forEach(t => S([[t[0]-t[1]*0.25,0],[t[0]+t[1]*0.25,0],[t[0]+t[1]*0.3,t[1]*2.6+250],[t[0]-t[1]*0.3,t[1]*2.6+250]], "#3a4a4e", 190, 0.25));
  S([[0,0],[600,0],[600,110],[0,150]], "#3d7a52", 200, 0.3);
  S([[0,0],[600,0],[600,60],[0,80]], "#20563a", 190, 0.3);
  S([[260,0],[340,0],[345,90],[255,95]], "#a8d4a0", 150, 0.3);
  for (let i = 0; i < 60; i++) { brush.fill("#8a6cd0", 200); brush.fillBleed(0.2); brush.circle((i * 79) % 600, 310 + (i * 41) % 290, 3 + (i % 5), 0.6); }
}

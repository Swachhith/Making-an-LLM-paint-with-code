async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function sh(c,o,b,k,a){brush.fill(c,o);brush.fillBleed(b);brush.fillTexture(0.5,0.4);brush.beginShape(k);for(const p of a)brush.vertex(p[0],p[1]);brush.endShape(true);}
function P2(c,o,a){brush.fill(c,o);brush.fillBleed(0.3);brush.beginShape(0.3);for(const p of a)brush.vertex(p[0],p[1]);brush.endShape(true);}

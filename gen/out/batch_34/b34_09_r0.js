async function setup() {
  createCanvas(600, 600, WEBGL);
  brush.scaleBrushes(3);
  angleMode(DEGREES);
  noLoop();
}

function P(c,o,b,pts,k){brush.fill(c,o);brush.fillBleed(b);brush.fillTexture(0.4,0.4);brush.beginShape(k);for(const p of pts)brush.vertex(p[0],p[1]);brush.endShape(true);}
function draw() {
  translate(-width / 2, -height / 2);
  background("#1b2a1e");
  brush.noStroke();
  P("#2a5a34",210,0.3,[[0,0],[600,0],[600,600],[0,600]],0.2);
  P("#103a22",210,0.3,[[0,250],[600,200],[600,600],[0,600]],0.3);
  P("#c8a030",190,0.3,[[400,50],[560,80],[540,220],[420,200]],0.7);
  for(let i=0;i<5;i++){P("#2f8a48",200,0.3,[[120+i*60,600],[140+i*60,330],[170+i*60,600]],0.5);}
  P("#3a8a50",200,0.3,[[100,600],[300,380],[320,600]],0.5);
  // side-view sweet pea
  P("#e8b830",230,0.3,[[200,200],[300,140],[380,200],[330,290],[240,280]],0.8);
  P("#f8d868",230,0.3,[[280,280],[360,250],[410,330],[340,380],[280,350]],0.8);
  P("#c88a18",230,0.3,[[220,250],[260,330],[230,390],[180,320]],0.8);
  P("#f4e098",220,0.25,[[260,190],[320,190],[320,250],[260,250]],0.8);
  P("#4a9a58",220,0.25,[[270,380],[310,390],[330,480],[290,470]],0.4);
  P("#e8b830",200,0.3,[[100,300],[160,260],[190,320],[130,360]],0.8);
}
